let currentLang = "en";

function t(key, vars) {
    const dict = I18N[currentLang] || I18N.en;
    let str = dict[key] ?? I18N.en[key] ?? key;
    if (vars && typeof vars === "object") {
        Object.keys(vars).forEach(k => {
            str = str.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
        });
    }
    return str;
}

function setLanguage(lang) {
    if (!I18N[lang]) lang = "en";
    currentLang = lang;
    try { localStorage.setItem("sqlibar_lang", lang); } catch (e) {}
    document.documentElement.lang = lang;
    applyI18n();
}

function applyI18n() {
    // data-i18n → textContent
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (!key) return;
        const val = t(key);
        if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
            // skip – placeholders handled separately
        } else if (el.tagName === "OPTION") {
            el.textContent = val;
        } else {
            el.textContent = val;
        }
    });

    // data-i18n-placeholder
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (key) el.placeholder = t(key);
    });

    // data-i18n-title
    document.querySelectorAll("[data-i18n-title]").forEach(el => {
        const key = el.getAttribute("data-i18n-title");
        if (key) el.title = t(key);
    });

    // data-i18n-html (for elements that need innerHTML, rare)
    document.querySelectorAll("[data-i18n-html]").forEach(el => {
        const key = el.getAttribute("data-i18n-html");
        if (key) el.innerHTML = t(key);
    });

    // optgroup labels
    document.querySelectorAll("optgroup[data-i18n-label]").forEach(el => {
        const key = el.getAttribute("data-i18n-label");
        if (key) el.label = t(key);
    });

    // Language select value
    const langSel = document.getElementById("langSelect");
    if (langSel) langSel.value = currentLang;

    // Version label prefix
    const verLabel = document.getElementById("addonVersionLabel");
    if (verLabel && verLabel.dataset.version) {
        verLabel.textContent = t("opt.version") + " " + verLabel.dataset.version;
    }

    // Refresh dynamic empty states if lists are empty
    const pageList = document.getElementById("pageParamList");
    if (pageList && pageList.querySelector(".param-empty")) {
        const empty = pageList.querySelector(".param-empty");
        if (empty) empty.textContent = t("page.empty");
    }
    const netList = document.getElementById("netParamList");
    if (netList && netList.querySelector(".param-empty")) {
        const empty = netList.querySelector(".param-empty");
        if (empty && !empty.textContent.includes("(")) empty.textContent = t("net.paramsEmpty");
    }
    const netEmpty = document.querySelector("#networkList .network-empty");
    if (netEmpty) netEmpty.textContent = t("net.empty");

    // Pause / Start network recording button
    const toggleNetBtn = document.getElementById("toggleNetRecording");
    if (toggleNetBtn) {
        const recording = (typeof isRecording !== "undefined") ? isRecording : !toggleNetBtn.classList.contains("btn-secondary");
        toggleNetBtn.textContent = recording ? t("net.pause") : t("net.start");
        toggleNetBtn.setAttribute("data-i18n", recording ? "net.pause" : "net.start");
    }

}

function initI18n() {
    let saved = "en";
    try { saved = localStorage.getItem("sqlibar_lang") || "en"; } catch (e) {}
    if (!I18N[saved]) saved = "en";
    currentLang = saved;
    document.documentElement.lang = saved;
    applyI18n();
}
